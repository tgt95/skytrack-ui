/**
 * Generates one CSF story file per demo (src/stories/<id>.stories.tsx).
 * Each DemoMeta variant becomes one story calling variant.render() by index.
 * Rerun after adding or changing a demo file: `node scripts/generate-stories.mjs`.
 * Never hand-write the 37 story files; this script owns them.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const demosDir = path.join(root, 'src', 'demos')
const outDir = path.join(root, 'src', 'stories')

/** Extracts balanced delimiters starting at index of the opening char. */
function balanced(text, start, open, close) {
  let depth = 0
  let inStr = null
  let escaped = false
  for (let i = start; i < text.length; i++) {
    const ch = text[i]
    if (inStr) {
      if (escaped) escaped = false
      else if (ch === '\\') escaped = true
      else if (ch === inStr) inStr = null
    } else if (ch === '"' || ch === "'" || ch === '`') {
      inStr = ch
    } else if (ch === open) {
      depth++
    } else if (ch === close) {
      depth--
      if (depth === 0) return text.slice(start, i + 1)
    }
  }
  return null
}

/** Matches a double- or single-quoted string literal value for `key:`; returns unescaped value. */
function strField(objText, key) {
  const m = objText.match(new RegExp(`${key}:\\s*("((?:[^"\\\\]|\\\\.)*)"|'((?:[^'\\\\]|\\\\.)*)')`, 's'))
  if (!m) return null
  if (m[2] !== undefined) return JSON.parse(`"${m[2]}"`)
  return unescapeSingle(m[3])
}

/** Unescapes the body of a single-quoted JS string literal. */
function unescapeSingle(raw) {
  return raw.replace(/\\(?:u([0-9a-fA-F]{4})|x([0-9a-fA-F]{2})|([\s\S]))/g, (_, u, x, ch) => {
    if (u !== undefined) return String.fromCharCode(parseInt(u, 16))
    if (x !== undefined) return String.fromCharCode(parseInt(x, 16))
    switch (ch) {
      case 'n': return '\n'
      case 'r': return '\r'
      case 't': return '\t'
      case 'b': return '\b'
      case 'f': return '\f'
      case 'v': return '\v'
      case '0': return '\0'
      case '\n': return ''
      default: return ch
    }
  })
}

function toExportName(name, taken) {
  let base = name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
  if (!base || /^[0-9]/.test(base)) base = `Variant${base}`
  if (base === '_') base = 'Variant'
  let candidate = base
  for (let n = 2; taken.has(candidate); n++) candidate = `${base}${n}`
  taken.add(candidate)
  return candidate
}

const files = readdirSync(demosDir)
  .filter((f) => f.endsWith('.demo.tsx'))
  .sort()
if (files.length === 0) {
  console.error('generate-stories: no src/demos/*.demo.tsx files found')
  process.exit(1)
}

mkdirSync(outDir, { recursive: true })
const failures = []
let storyCount = 0

for (const file of files) {
  const base = file.replace(/\.demo\.tsx$/, '')
  const text = readFileSync(path.join(demosDir, file), 'utf8')
  const anchor = text.indexOf('export const demo')
  const objStart = anchor === -1 ? -1 : text.indexOf('{', text.indexOf('=', anchor))
  const objText = objStart === -1 ? null : balanced(text, objStart, '{', '}')
  const id = objText && strField(objText, 'id')
  const title = objText && strField(objText, 'title')
  const description = objText && strField(objText, 'description')
  const group = objText && strField(objText, 'group')
  let variantNames = []
  if (objText) {
    const vAnchor = objText.indexOf('variants:')
    const arrStart = vAnchor === -1 ? -1 : objText.indexOf('[', vAnchor)
    const arrText = arrStart === -1 ? null : balanced(objText, arrStart, '[', ']')
    if (arrText) {
      for (const m of arrText.matchAll(/\{\s*name:\s*("((?:[^"\\]|\\.)*)"|'((?:[^'\\]|\\.)*)')/g)) {
        variantNames.push(m[2] !== undefined ? JSON.parse(`"${m[2]}"`) : unescapeSingle(m[3]))
      }
    }
  }
  if (!id || !title || !group || variantNames.length === 0) {
    failures.push(`${file} (parsed id=${id} title=${title} group=${group} variants=${variantNames.length})`)
    continue
  }

  const taken = new Set()
  const stories = variantNames.map((name, i) => {
    const exportName = toExportName(name, taken)
    const lit = JSON.stringify(name)
    return `export const ${exportName}: Story = {\n  name: ${lit},\n  render: () => <VariantBlock name={${lit}}>{demo.variants[${i}].render()}</VariantBlock>,\n};`
  })

  const content = `// AUTO-GENERATED by scripts/generate-stories.mjs — do not edit directly.
// Rerun \`node scripts/generate-stories.mjs\` after adding or changing a demo file.
import type { Meta, StoryObj } from "@storybook/react-vite";
import { VariantBlock } from "../showcase/demo";
import { demo } from "../demos/${base}.demo";

const meta = {
  title: ${JSON.stringify(`${group}/${title}`)},
  parameters: { docs: { description: { component: ${JSON.stringify(description ?? '')} } } },
} satisfies Meta;

export default meta;
type Story = StoryObj;

${stories.join('\n\n')}
`
  writeFileSync(path.join(outDir, `${id}.stories.tsx`), content)
  storyCount++
}

if (failures.length > 0) {
  console.error(`generate-stories: failed to parse ${failures.length} demo file(s):\n- ${failures.join('\n- ')}`)
  process.exit(1)
}
console.log(`generate-stories: wrote ${storyCount} story files from ${files.length} demos`)
